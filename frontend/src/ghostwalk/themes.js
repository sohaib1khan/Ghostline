export function gameMeta(language) {
  return GHOSTWALK_GAMES.find((item) => item.id === language) || GHOSTWALK_GAMES[0];
}

export function themeFor(language, { farm = false, contrast = "default" } = {}) {
  const base = THEMES[language] || THEMES.python;
  if (contrast === "high" || contrast === "high-light" || contrast === "high-dark") {
    return { ...base, palette: { ...HIGH_CONTRAST }, highContrast: true };
  }
  if (farm) {
    return { ...base, id: `${base.id}-farm`, farm: true };
  }
  return base;
}

/** Map engine move messages to themed nouns for the Moves list. */
export function themeMoveMessage(theme, frame) {
  if (!frame) return "";
  const kind = frame.kind || "";
  const words = theme?.words || THEMES.python.words;
  if (kind === "move") return `${words.move}.`;
  if (kind === "turn") return frame.message || `${words.turn}.`;
  if (kind === "pick_up") return `${words.pick_up}.`;
  if (kind === "plant") return `${words.plant}.`;
  if (kind === "water") return `${words.water}.`;
  if (kind === "harvest") return `${words.harvest}.`;
  if (kind === "goal" || (kind === "start" && false)) return `${words.goal}.`;
  if (frame.message && /goal|lantern|barn|console|desk|lift|pod|roaster|cabinet/i.test(frame.message)) {
    return `${words.goal}.`;
  }
  return frame.message || "";
}
